function add(a: number, b: number): number {
  return a + b;
}

function sub(a: number, b: number): number {
  return a - b;
}

function mul(a: number, b: number): number {
  return a * b;
}

function div(a: number, b: number): number {
  return a / b;
}

console.log(add(4, 5));
console.log(sub(9, 5));
console.log(mul(9, 5));
console.log(div(10, 5));